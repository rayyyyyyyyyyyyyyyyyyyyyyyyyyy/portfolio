const CELL = 10;

function StitchTitle({ children, thread = 'pink', as: Tag = 'h2', id }) {
  const text = String(children).toUpperCase();
  const stitches = [];
  let x = 0;

  for (const ch of text) {
    const glyph = GLYPHS[ch] || GLYPHS[' '];
    for (let r = 0; r < glyph.length; r++) {
      for (let c = 0; c < glyph[r].length; c++) {
        if (glyph[r][c] === '#') stitches.push([x + c, r]);
      }
    }
    x += glyph[0].length + 1;
  }

  const cols = x - 1;
  const w = cols * CELL;
  const h = 7 * CELL;
  const pad = 4;

  return (
    <Tag className={`stitch-title stitch-title--${thread}`} id={id}>
      <span className="visually-hidden">{children}</span>
      <svg
        className="stitch-title__art"
        viewBox={`${-pad} ${-pad} ${w + pad * 2} ${h + pad * 2}`}
        style={{ '--cols': cols }}
        aria-hidden="true"
        focusable="false"
      >
        {stitches.map(([cx, cy]) => {
          const x0 = cx * CELL + 2;
          const y0 = cy * CELL + 2;
          const x1 = x0 + CELL - 4;
          const y1 = y0 + CELL - 4;
          return (
            <g key={`${cx}-${cy}`}>
              <line className="stitch-under" x1={x0} y1={y1} x2={x1} y2={y0} />
              <line className="stitch-over" x1={x0} y1={y0} x2={x1} y2={y1} />
            </g>
          );
        })}
      </svg>
    </Tag>
  );
}

export default StitchTitle;
